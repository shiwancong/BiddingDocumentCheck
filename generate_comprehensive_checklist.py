def extract_paragraph_by_keywords(json_data: dict, keywords: List[str]) -> List[Dict]:
    """根据关键词从JSON数据中提取段落"""
    results = []
    for item in json_data['content']:
        if item['type'] == 'paragraph':
            text = item['text']
            for keyword in keywords:
                if keyword in text:
                    results.append({
                        'index': item['index'],
                        'text': text,
                        'keyword': keyword
                    })
                    break
    return results

def search_content_by_page_range(json_data: dict, page_ranges: List[tuple]) -> List[Dict]:
    """根据页码范围搜索内容（基于段落索引估算）"""
    # 假设每页约35个段落
    paragraphs_per_page = 35
    results = []

    for page_start, page_end in page_ranges:
        index_start = page_start * paragraphs_per_page
        index_end = page_end * paragraphs_per_page

        for item in json_data['content']:
            if item['type'] == 'paragraph' and index_start <= item['index'] <= index_end:
                results.append({
                    'page_range': (page_start, page_end),
                    'index': item['index'],
                    'text': item['text']
                })

    return results

